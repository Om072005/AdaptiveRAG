from typing import Any

from adaptiverag.eval import single_hop
from adaptiverag.ingest.normalize import join_sentences
from adaptiverag.types import Document, LLMResult


def doc(title: str, sentences: list[str]) -> Document:
    text, spans = join_sentences(sentences)
    return Document(f"id_{title.lower()}", "hotpotqa-dev", title, text, spans)


BETA = doc("Beta", ["Beta City is a town in Ohio.", "It was founded in 1850 by settlers."])


def result(text: str) -> LLMResult:
    return LLMResult(text, "large", "openai/gpt-oss-120b", 10, 5, 0.0, 1, False, False, 0, 0)


def test_pick_documents_is_seeded_and_skips_one_sentence_paragraphs() -> None:
    docs = [doc(f"T{i}", ["One.", "Two."]) for i in range(10)] + [doc("Short", ["Only."])]
    picked = single_hop.pick_documents(docs, 4)
    assert len(picked) == 4 and all(d.title != "Short" for d in picked)
    assert picked == single_hop.pick_documents(list(reversed(docs)), 4)


def test_messages_number_the_sentences() -> None:
    content = single_hop.build_messages(BETA)[0]["content"]
    assert "Title: Beta\n[0] Beta City is a town in Ohio.\n[1] It was founded in 1850" in content


def test_parse_item_builds_a_single_hop_gold_item() -> None:
    raw = '{"question": "When was Beta City founded?", "answer": "1850", "sentence": 1}'
    item = single_hop.parse_item(raw, BETA, "note")
    assert not isinstance(item, str)
    assert item.id == "sh_id_beta_1" and item.type == "single_hop" and item.source == "generated"
    assert item.supporting_titles == ["Beta"] and item.supporting_sentences == [("Beta", 1)]


def test_parse_item_rejects_bad_output() -> None:
    assert single_hop.parse_item("not json", BETA, "") == "bad_json"
    assert single_hop.parse_item('{"question": "q"}', BETA, "") == "bad_json"
    bad_index = '{"question": "q?", "answer": "1850", "sentence": 5}'
    assert single_hop.parse_item(bad_index, BETA, "") == "bad_sentence"
    wrong_sentence = '{"question": "q?", "answer": "1850", "sentence": 0}'
    assert single_hop.parse_item(wrong_sentence, BETA, "") == "answer_not_in_sentence"


def test_generate_uses_large_role_and_records_temperature() -> None:
    calls: list[dict[str, Any]] = []

    def fake_chat(role: str, messages: list[dict[str, str]], **kw: Any) -> LLMResult:
        calls.append({"role": role, **kw})
        if len(calls) == 1:
            return result(
                '{"question": "When was Beta City founded?", "answer": "1850", "sentence": 1}'
            )
        return result("{}")

    items, rejects = single_hop.generate([BETA, doc("Gamma", ["A.", "B."])], fake_chat, 0.7)
    assert calls[0]["role"] == "large" and calls[0]["temperature"] == 0.7 and calls[0]["json_mode"]
    assert [i.id for i in items] == ["sh_id_beta_1"]
    assert items[0].notes == "generated by openai/gpt-oss-120b at temperature 0.7"
    assert rejects == [("id_gamma", "bad_json")]


def test_names_subject_needs_a_title_word_in_the_question() -> None:
    title = "2013 FIBA Americas Championship"
    assert not single_hop.names_subject("In which city was the tournament held?", title)
    assert single_hop.names_subject("Where was the 2013 FIBA Americas Championship held?", title)
    assert not single_hop.names_subject(
        "How many people does the film follow?", "Night Moves (2013 film)"
    )
    assert single_hop.names_subject("Who directed Night Moves?", "Night Moves (2013 film)")


def test_parse_item_strips_quotes_and_rejects_subjectless_questions() -> None:
    raw = '{"question": "When was Beta City founded?", "answer": "\\"1850\\"", "sentence": 1}'
    item = single_hop.parse_item(raw, BETA, "")
    assert not isinstance(item, str) and item.answer == "1850"
    vague = '{"question": "When was the town founded?", "answer": "1850", "sentence": 1}'
    assert single_hop.parse_item(vague, BETA, "") == "question_lacks_subject"
