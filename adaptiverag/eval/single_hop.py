"""Single hop gold candidates generated from one corpus paragraph by the 'large' role."""

import json
import random
from collections.abc import Callable

from adaptiverag.eval.gold import GoldItem
from adaptiverag.eval.metrics import normalize_answer
from adaptiverag.types import Document, LLMResult

ChatFn = Callable[..., LLMResult]

PROMPT = """You write one question for a question answering test set.
Read the paragraph. Pick one numbered sentence and write a question only that sentence answers.
The question must name its subject in full, using the words of the title (never "the film",
"the tournament" or "it"), so it makes sense without the paragraph.
The question must have exactly one correct answer (never "one of the ...").
The answer is the shortest span copied exactly from that sentence (a name, date, place or number).
Reply with JSON only: {{"question": "...", "answer": "...", "sentence": <sentence number>}}

Title: {title}
{sentences}"""


def pick_documents(docs: list[Document], n: int, seed: int = 7) -> list[Document]:
    """n paragraphs with at least two sentences, in a seeded order that ignores input order."""
    pool = sorted((d for d in docs if len(d.sentences) >= 2), key=lambda d: d.doc_id)
    random.Random(seed).shuffle(pool)
    return pool[:n]


def build_messages(doc: Document) -> list[dict[str, str]]:
    lines = "\n".join(f"[{i}] {doc.text[s:e]}" for i, (s, e) in enumerate(doc.sentences) if e > s)
    return [{"role": "user", "content": PROMPT.format(title=doc.title, sentences=lines)}]


def names_subject(question: str, title: str) -> bool:
    """True when the question contains a word of the title, ignoring any bracketed part."""
    words = {
        w for w in normalize_answer(title.split("(")[0]).split() if len(w) >= 3 and w.isalpha()
    }
    return not words or bool(words & set(normalize_answer(question).split()))


def parse_item(raw: str, doc: Document, note: str) -> GoldItem | str:
    """A single hop GoldItem, or the reason the model output is rejected."""
    try:
        data = json.loads(raw)
        question, answer, i = (
            str(data["question"]).strip(),
            # models sometimes wrap the copied span in quotes
            str(data["answer"]).strip().strip("\"'“”‘’").strip(),
            data["sentence"],
        )
    except (ValueError, KeyError, TypeError):
        return "bad_json"
    if not isinstance(i, int) or not 0 <= i < len(doc.sentences):
        return "bad_sentence"
    start, end = doc.sentences[i]
    if (
        not question
        or not answer
        or normalize_answer(answer) not in normalize_answer(doc.text[start:end])
    ):
        return "answer_not_in_sentence"
    if not names_subject(question, doc.title):
        return "question_lacks_subject"
    return GoldItem(
        id=f"sh_{doc.doc_id}_{i}",
        question=question,
        answer=answer,
        type="single_hop",
        split="",
        supporting_titles=[doc.title],
        supporting_sentences=[(doc.title, i)],
        source="generated",
        notes=note,
    )


def generate(
    docs: list[Document], chat: ChatFn, temperature: float
) -> tuple[list[GoldItem], list[tuple[str, str]]]:
    """One question per paragraph; returns the items and (doc_id, reason) for each reject."""
    items, rejects = [], []
    for doc in docs:
        r = chat(
            "large", build_messages(doc), json_mode=True, temperature=temperature, max_tokens=1024
        )
        got = parse_item(r.text, doc, f"generated by {r.model} at temperature {temperature}")
        if isinstance(got, str):
            rejects.append((doc.doc_id, got))
        else:
            items.append(got)
    return items, rejects
